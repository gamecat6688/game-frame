"""Configure this checkout's Godot client for the running local Compose server."""
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def compose(*args):
    return subprocess.check_output(
        ['docker', 'compose', *args], cwd=ROOT, text=True, encoding='utf-8'
    ).strip()


def main():
    config = json.loads(compose('config', '--format', 'json'))
    token = Path(config['secrets']['game_token']['file']).read_text(encoding='utf-8').strip()
    if not token or len(token.encode()) > 4096 or any(c in token for c in '\r\n\x00'):
        raise SystemExit('Invalid Docker token file')
    address = compose('port', 'server', '18080').splitlines()[0]
    host, port = address.rsplit(':', 1)
    if host in ('0.0.0.0', '::', '[::]'):
        host = '127.0.0.1'
    url = f'ws://{host}:{int(port)}/ws'
    path = ROOT / 'client/override.cfg'
    path.write_text(
        '; Local Docker connection; generated by tools/configure_docker_client.py.\n'
        '; Ignored by Git. Re-run after changing the server port or token.\n'
        '[game]\n'
        f'server_url={json.dumps(url)}\n'
        f'development_token={json.dumps(token)}\n',
        encoding='utf-8',
    )
    print(f'Configured local client: {url}; restart Godot to apply. Token was not printed.')


if __name__ == '__main__':
    main()
